import React, { createContext, useContext, useEffect, useState } from 'react';
import { recordDid } from './NotificationsContext';
import { collection, onSnapshot, addDoc, doc, deleteDoc, updateDoc, writeBatch, query, where, arrayUnion } from 'firebase/firestore';
import { db, auth } from '../firebaseConfig';
import { brandOfLocation } from '../data/brandOfLocation';
import { useAuth } from './AuthContext';
import { getTemplateForLocation } from '../data/checklists';
import { blockersOf, unblockedWrites, DAY } from '../lib/openingPlan';

const ScheduleContext = createContext(undefined);
const COLLECTION = 'schedules';

// Start of today, local time — the "floor" any overdue opening item gets
// rolled forward to.
function startOfToday() {
  const d = new Date();
  d.setHours(0, 0, 0, 0);
  return d.getTime();
}

export function ScheduleProvider({ children }) {
  const [entries, setEntries] = useState([]);
  const { user } = useAuth();

  useEffect(() => {
    if (!user) {
      setEntries([]);
      return;
    }
    // Checklist items, renewal tasks and calendar entries all live here, and
    // every one carries a location. Only the restaurants this person has -
    // before, every location's sat in every browser.
    const seesAll = user.role === 'admin' || user.role === 'executive';
    const mine = user.permissions?.brandIds ?? [];
    if (!seesAll && mine.length === 0) {
      setEntries([]);
      return;
    }
    const source = seesAll
      ? collection(db, COLLECTION)
      : query(collection(db, COLLECTION), where('brandId', 'in', mine.slice(0, 30)));

    const unsubscribe = onSnapshot(source, (snapshot) => {
      const list = snapshot.docs.map((d) => {
        const data = d.data();
        return {
          id: d.id,
          locationId: data.locationId,
          title: data.title,
          dateTime: data.dateTime,
          note: data.note ?? '',
          authorName: data.authorName,
          authorUid: data.authorUid ?? null,
          timestamp: data.timestamp,
          // Present only on entries generated by the Opening Checklist —
          // regular calendar entries just won't have these fields at all.
          // Storing checklist items as schedule entries (rather than a
          // separate collection with its own copy) is what guarantees the
          // Checklist screen and the Calendar can never drift out of sync —
          // there's only ever one document per task.
          openingItem: data.openingItem ?? false,
          openingItemType: data.openingItemType ?? null, // 'timeline' | 'setup'
          openingSection: data.openingSection ?? null,
          openingFields: data.openingFields ?? null, // { company, accountNumber, contact } — setup items only
          setupKey: data.setupKey ?? null, // links a setup item back to its template entry, for dependency lookups
          // Written by the three people who can restructure a checklist. Read
          // back here or the panel shows nothing and the home screen cannot
          // find work assigned to someone.
          assignedToUid: data.assignedToUid ?? null,
          assignedToName: data.assignedToName ?? null,
          assignedToUids: Array.isArray(data.assignedToUids) ? data.assignedToUids : null,
          assignedToNames: Array.isArray(data.assignedToNames) ? data.assignedToNames : null,
          // Other items at this location that must be signed off first. Set on
          // the record rather than in the template, because an item added in
          // the app has no template entry - and a permit in one city can
          // depend on something that does not exist in another.
          dependsOnIds: data.dependsOnIds ?? null,
          templateId: data.templateId ?? null, // which city template produced this item
          // The permit or certificate itself: { url, path, name, uploadedAt,
          // uploadedBy }. Lives on the task that produced it, and gets copied
          // to the renewal record on sign-off so it's there at renewal time.
          document: data.document ?? null,
          // Every document on the task (10 Oct 2026); absent on older items.
          documents: data.documents ?? null,
          // "Needs a signature from…" - { requestedOfUid, requestedOfName,
          // requestedByUid, requestedByName, requestedAt, note, status:
          // 'waiting' | 'signed' | 'sentBack', signedAt, backNote }.
          signature: data.signature ?? null,
          renewalItem: data.renewalItem ?? false, // the migrated license/permit's initial "get this" calendar task
          renewalType: data.renewalType ?? null, // matches a type in renewalTypes.js
          done: data.done ?? false,
          doneBy: data.doneBy ?? null,
          doneAt: data.doneAt ?? null,
          // Set the first time an item goes overdue and stays set (even as
          // dateTime keeps getting rolled to today) until it's signed off —
          // this is what makes the urgent badge distinct from something
          // that's simply due today for the first time.
          attentionFlag: data.attentionFlag ?? false,
          // The re-plan (19 Oct 2026, sketch 24). lateSince: the date it was
          // due when it first went late. slidWhileWaiting: its date went by
          // while it waited on another item, so it gets a fresh date once
          // free. dateSetByHand: someone chose this date; the plan keeps it.
          lateSince: data.lateSince ?? null,
          slidWhileWaiting: data.slidWhileWaiting ?? false,
          dateSetByHand: data.dateSetByHand ?? false,
          atRisk: data.atRisk ?? false,
          planGapDays: data.planGapDays ?? null,
          replannedAt: data.replannedAt ?? null,
        };
      });
      setEntries(list);

      // Roll forward any un-signed-off opening item whose date has passed.
      // Runs once per snapshot per session (guarded so it doesn't refire on
      // every render) and is safe if two devices both run it — worst case
      // is a redundant, idempotent write.
      const today = startOfToday();
      // Waiting is not late (19 Oct 2026): an item that cannot start because
      // something it waits on is not done slides along with today but is
      // never flagged; once free it gets the time it was planned to have.
      // Only an item that could have been done and wasn't is flagged.
      const setupAt = {};
      list.forEach((e) => { if (e.openingItem && e.openingItemType === 'setup') (setupAt[e.locationId] ??= []).push(e); });
      const blocked = (e) => {
        if (!e.openingItem || e.openingItemType !== 'setup') return false;
        try { return blockersOf(e, setupAt[e.locationId] ?? [], getTemplateForLocation(e.locationId)).length > 0; } catch { return false; }
      };
      const writes = [];
      list.forEach((e) => {
        if (!(e.openingItem || e.renewalItem) || e.done) return;
        const isBlocked = blocked(e);
        if (e.dateTime < today) {
          if (isBlocked) writes.push([e.id, { dateTime: today, attentionFlag: false, slidWhileWaiting: true }]);
          else if (e.slidWhileWaiting) {
            const d = new Date(today + (e.planGapDays ?? 3) * DAY); d.setHours(12, 0, 0, 0);
            writes.push([e.id, { dateTime: d.getTime(), attentionFlag: false, slidWhileWaiting: false }]);
          } else writes.push([e.id, { dateTime: today, attentionFlag: true, ...(e.attentionFlag ? {} : { lateSince: e.dateTime }) }]);
        } else if (e.attentionFlag && isBlocked) {
          // Flagged before waiting counted: take the flag off.
          writes.push([e.id, { attentionFlag: false, slidWhileWaiting: true }]);
        }
      });
      if (writes.length > 0) {
        const batch = writeBatch(db);
        writes.forEach(([id, fields]) => batch.update(doc(db, COLLECTION, id), fields));
        batch.commit().catch(() => {
          // Fine to lose this race silently — another client's snapshot
          // will pick up the same overdue set and retry.
        });
      }
    },
      (err) => console.error('[Schedule listener] ' + err.code + ': ' + err.message)
    );
    return unsubscribe;
  }, [user]);

  const addEntry = async (params) => {
    await addDoc(collection(db, COLLECTION), {
      ...params,
      // Stamped so this entry can be found by restaurant.
      brandId: await brandOfLocation(params.locationId),
      authorUid: auth.currentUser?.uid ?? null,
      timestamp: Date.now(),
    });
  };

  const deleteEntry = async (id) => {
    await deleteDoc(doc(db, COLLECTION, id));
  };

  const updateEntry = async (id, updates) => {
    await updateDoc(doc(db, COLLECTION, id), updates);
  };

  // Marks (or unmarks) an opening-checklist item done — since it IS the
  // calendar entry, this is the exact same action whether triggered from
  // the Checklist screen or the Calendar screen.
  const toggleOpeningItemDone = async (id, done, doneByName) => {
    const at = Date.now();
    await updateDoc(doc(db, COLLECTION, id), {
      done,
      doneBy: done ? doneByName : null,
      doneAt: done ? at : null,
      // Every tick and untick, kept on the item itself, so who signed it off
      // and when can always be answered - even if it is later unticked.
      signOffHistory: arrayUnion({ done, by: doneByName ?? 'Unknown', at }),
    });
    // So "did I tick that off" has an answer - naming the item this time.
    const item = entries.find((e) => e.id === id);
    if (done && item) await releaseWaiting(item);
    if (done) recordDid('You signed off: ' + (item?.title ?? 'a checklist item'), item?.locationId ?? '', '/calendar');
  };

  // After a sign-off: items that were waiting on it get their fresh dates.
  // Best effort - the daily roll-forward catches anything this misses.
  const releaseWaiting = async (item) => {
    try {
      const writes = unblockedWrites(item, entries.filter((e) => e.locationId === item.locationId && e.openingItem));
      if (!writes.length) return;
      const batch = writeBatch(db);
      writes.forEach(([wid, fields]) => batch.update(doc(db, COLLECTION, wid), fields));
      await batch.commit();
    } catch (err) {
      console.warn('[Schedule] could not re-date waiting items: ' + (err?.message ?? err));
    }
  };

  const getByLocation = (locationId) =>
    entries.filter((e) => e.locationId === locationId).sort((a, b) => a.dateTime - b.dateTime);

  const getByLocations = (locationIds) =>
    entries.filter((e) => locationIds.includes(e.locationId)).sort((a, b) => a.dateTime - b.dateTime);

  const getOpeningItemsByLocation = (locationId) =>
    entries.filter((e) => e.locationId === locationId && e.openingItem).sort((a, b) => a.dateTime - b.dateTime);

  return (
    <ScheduleContext.Provider
      value={{
        entries,
        addEntry,
        updateEntry,
        deleteEntry,
        getByLocation,
        getByLocations,
        getOpeningItemsByLocation,
        toggleOpeningItemDone,
        releaseWaiting,
      }}
    >
      {children}
    </ScheduleContext.Provider>
  );
}

export function useSchedule() {
  const ctx = useContext(ScheduleContext);
  if (!ctx) throw new Error('useSchedule must be used within ScheduleProvider');
  return ctx;
}
